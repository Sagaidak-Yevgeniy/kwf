const dicts: Record<Lang, Dict> = { ru, kk };
const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: string) => string }>({
  lang: 'ru', setLang: () => {}, t: (k) => k,
});

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem('kwf-lang') as Lang) || 'ru');
  const setLang = (l: Lang) => { setLangState(l); localStorage.setItem('kwf-lang', l); };
  useEffect(() => { document.documentElement.lang = lang === 'kk' ? 'kk' : 'ru'; }, [lang]);
  const t = (k: string) => dicts[lang][k] ?? ru[k] ?? k;
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export const useLang = () => useContext(Ctx);
export const getLang = (): Lang => (localStorage.getItem('kwf-lang') as Lang) || 'ru';

export function LangToggle() {
  const { lang, setLang } = useLang();
  return (
    <div className="flex rounded-lg overflow-hidden text-[12px] font-extrabold" style={{ border: '1px solid var(--border)' }} role="group" aria-label="Тіл / Язык">
      {(['ru', 'kk'] as Lang[]).map(l => (
        <button key={l} onClick={() => setLang(l)} aria-pressed={lang === l} className="px-2.5 py-1.5 uppercase"
                style={lang === l ? { background: 'var(--accent)', color: '#05080D' } : { color: 'var(--muted)' }}>
          {l === 'ru' ? 'Рус' : 'Каз'}
        </button>
      ))}
    </div>
  );
}
